    private void jButtonInsertActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonInsertActionPerformed
        try {
            Line line = new Line();
            line.setId(Integer.parseInt(jTextFieldId.getText()));
            line.setName(jTextFieldName.getText());
            
            lineController.insert(line);
            MessageUtils.getInstance().showInfo("El registro fue creado exitosamente");
            clear();
            fillTable();
        } catch (NumberFormatException ex) {
            MessageUtils.getInstance().showError("El numero del galpon debe contener solo numeros");
        }
        catch (Exception ex) {
            MessageUtils.getInstance().showError(ex.getMessage());
        }
    }//GEN-LAST:event_jButtonInsertActionPerformed

    private void jButtonDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDeleteActionPerformed
        int option = MessageUtils.getInstance().showComfirm("Esta seguro de eliminar el registro");
        if (option == JOptionPane.YES_OPTION)
        {
            try {
                lineController.delete(Integer.parseInt(jTextFieldId.getText()));
                MessageUtils.getInstance().showInfo("Registro eliminado exitosamente");
                clear();
                fillTable();
            } catch (Exception ex) {
                MessageUtils.getInstance().showError(ex.getMessage());
            }
        }
    }//GEN-LAST:event_jButtonDeleteActionPerformed

    private void jTableLineMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableLineMouseClicked
        int rowSelected = jTableLine.getSelectedRow();
        if(rowSelected != -1)
        {
            jButtonUpdate.setEnabled(true);
            jButtonDelete.setEnabled(true);
            jButtonInsert.setEnabled(false);
            
            int numberSelected = Integer.parseInt(jTableLine.getValueAt(rowSelected, 0).toString());
            try {
                //consultar por id
                Line line = lineController.find(numberSelected);
                jTextFieldId.setText(String.valueOf(line.getId()));
                jTextFieldName.setText(line.getName());
            } catch (Exception ex) {
                MessageUtils.getInstance().showError(ex.getMessage());
            }
        }
    }//GEN-LAST:event_jTableLineMouseClicked

    private void jButtonUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonUpdateActionPerformed
        try {
            Line line = new Line();
            line.setId(Integer.parseInt(jTextFieldId.getText()));
            line.setName(jTextFieldName.getText());
            lineController.update(line);
            MessageUtils.getInstance().showInfo("El registro fue modificado exitosamente");
            clear();
            fillTable();
        } catch (NumberFormatException ex) {
            MessageUtils.getInstance().showError("El número de la linea debe contener solo números");
        } catch (Exception ex) {
            MessageUtils.getInstance().showError(ex.getMessage());
        }
    }//GEN-LAST:event_jButtonUpdateActionPerformed

    
